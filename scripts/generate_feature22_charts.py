# 4. Total Wire Bytes Transmitted by Representation
fig, ax = plt.subplots(figsize=(8, 5))
baseline_df = df[df['conditionName'] == 'LOSS_0%']
reps = ['FULL', 'COMPACT', 'SEMANTIC_ENHANCED', 'CONTEXT_DELTA', 'SEMANTIC_BASE']
bytes_vals = [baseline_df[baseline_df['representation'] == r]['bytesTransmitted'].values[0] for r in reps]
bar_colors = [colors[r] for r in reps]

bars = ax.bar(reps, bytes_vals, color=bar_colors, width=0.55, edgecolor='black', linewidth=0.8)
for bar, val in zip(bars, bytes_vals):
    yval = bar.get_height()
    reduction = ((bytes_vals[0] - val) / bytes_vals[0]) * 100 if bytes_vals[0] > 0 else 0
    label = f"{val} B" if reduction <= 0 else f"{val} B\n(-{reduction:.1f}%)"
    ax.text(bar.get_x() + bar.get_width()/2.0, yval + 15, label, ha='center', va='bottom', fontsize=9, fontweight='bold')

ax.set_title("iTantra: Total Wire Bytes for 6-Message Tactical Corpus", fontweight='bold')
ax.set_ylabel("Total Bytes Transmitted on Wire (Header + Auth + Payload)")
ax.set_ylim(0, max(bytes_vals) * 1.25)
plt.tight_layout()
plt.savefig(os.path.join(output_dir, "bytes_by_representation.png"))
plt.close()

