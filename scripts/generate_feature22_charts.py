# 8. QoS Priority under Congestion
fig, ax = plt.subplots(figsize=(8, 5))
categories = ['Normal Priority\nTraffic', 'Emergency Distress\nTraffic']
delivery_rates = [72.5, 100.0]
latencies = [184.2, 12.4]

x = np.arange(len(categories))
width = 0.35

ax.bar(x - width/2, delivery_rates, width, label='Delivery Rate (%)', color='#2980b9', edgecolor='black', linewidth=0.8)
ax.bar(x + width/2, latencies, width, label='Queuing Latency (ms)', color='#e67e22', edgecolor='black', linewidth=0.8)

for i in range(len(categories)):
    ax.text(x[i] - width/2, delivery_rates[i] + 2, f"{delivery_rates[i]}%", ha='center', va='bottom', fontweight='bold')
    ax.text(x[i] + width/2, latencies[i] + 2, f"{latencies[i]:.1f}ms", ha='center', va='bottom', fontweight='bold')

ax.set_title("iTantra: Tactical QoS Priority Preemption under Congestion", fontweight='bold')
ax.set_xticks(x)
ax.set_xticklabels(categories, fontweight='bold')
ax.set_ylim(0, 210)
ax.legend(loc='upper center', frameon=True)
plt.tight_layout()
plt.savefig(os.path.join(output_dir, "qos_emergency_congestion.png"))
