import os
import pandas as pd
import matplotlib.pyplot as plt
import numpy as np

output_dir = os.path.join("docs", "benchmark", "charts")
os.makedirs(output_dir, exist_ok=True)

plt.style.use('seaborn-v0_8-whitegrid' if 'seaborn-v0_8-whitegrid' in plt.style.available else 'default')
plt.rcParams['font.family'] = 'sans-serif'
plt.rcParams['font.size'] = 10
plt.rcParams['axes.titlesize'] = 12
plt.rcParams['axes.labelsize'] = 11
plt.rcParams['figure.dpi'] = 300

colors = {
    'FULL': '#2b5c8f',
    'COMPACT': '#3a8891',
    'SEMANTIC_BASE': '#d9534f',
    'SEMANTIC_ENHANCED': '#8e44ad',
    'CONTEXT_DELTA': '#27ae60'
}

df = pd.read_csv("feature22_results.csv")

# 1. Delivery Success Rate vs Loss Rate
fig, ax = plt.subplots(figsize=(8, 5))
loss_conditions = ['LOSS_0%', 'LOSS_5%', 'LOSS_10%', 'LOSS_20%', 'LOSS_30%', 'LOSS_50%']
loss_df = df[df['conditionName'].isin(loss_conditions)].copy()
loss_df['loss_pct'] = loss_df['configuredLossRate'] * 100

for rep in ['FULL', 'COMPACT', 'SEMANTIC_BASE', 'SEMANTIC_ENHANCED', 'CONTEXT_DELTA']:
    sub = loss_df[loss_df['representation'] == rep].sort_values('loss_pct')
    ax.plot(sub['loss_pct'], sub['deliverySuccessRate'] * 100, marker='o', linewidth=2.2, label=rep, color=colors[rep])

ax.set_title("iTantra: Message Delivery Rate vs. Packet Loss Rate (Controlled Simulation)", fontweight='bold')
ax.set_xlabel("Configured Channel Packet Loss Rate (%)")
ax.set_ylabel("Message Delivery Success Rate (%)")
ax.set_ylim(0, 105)
ax.legend(title="Adaptive Mode", loc="lower left", frameon=True)
plt.tight_layout()
plt.savefig(os.path.join(output_dir, "delivery_vs_loss.png"))
plt.close()

